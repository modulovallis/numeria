/// A small, dependency-free localization system.
///
/// A production build would likely move to ARB files + `flutter gen-l10n`
/// once translators are working directly in a translation-management tool,
/// but a plain Dart map keeps this prototype easy to read end-to-end and
/// avoids relying on generated code that a reviewer can't see.
class AppLocalizations {
  AppLocalizations(this.locale);

  final Locale locale;

  static AppLocalizations of(BuildContext context) {
    final loc = Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(loc != null, 'AppLocalizations not found in context');
    return loc!;
  }

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  String _raw(String key) {
    final langMap = _strings[locale.languageCode] ?? _strings['en']!;
    return langMap[key] ?? _strings['en']![key] ?? key;
  }

  /// Looks up [key] for the current locale, replacing any `{name}`
  /// placeholders with the matching entry from [params].
  String t(String key, [Map<String, Object>? params]) {
    var value = _raw(key);
    params?.forEach((k, v) {
      value = value.replaceAll('{$k}', '$v');
    });
    return value;
  }
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) =>
      kSupportedLocales.any((l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async => AppLocalizations(locale);

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

/// Convenience accessor: `context.l10n.t('play_button')`.
extension AppLocalizationsX on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

